## El chip: el primero de 2 nanómetros

El **A20 Pro** es el primer chip de un teléfono fabricado en un proceso de 2 nanómetros.

Traducido: entran más transistores en el mismo espacio y cada uno gasta menos. En la práctica se nota más en la batería y en el calor que en la velocidad — un iPhone Pro de hace dos años ya abría cualquier app al instante. Lo que mejora es cuánto aguanta haciendo eso.

