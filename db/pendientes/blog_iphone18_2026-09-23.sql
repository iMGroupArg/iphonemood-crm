## La cámara: la apertura variable es la novedad real

Esta es la que sí cambia cómo se saca una foto.

Hasta ahora, la apertura del lente del iPhone era fija: el teléfono compensaba todo por software. El 18 Pro estrena una **apertura variable de f/1.48 a f/4**, o sea que el diafragma se abre y se cierra de verdad, como en una cámara.

